"""MTP self-speculative decode through the generator (`Glm53Generator(spec=True)`: the warm-up's captures, the traced
prefill with the MTP layer's cache and each prompt's first draft, `verify`), the way serving takes it: the 11 greedy
records' prompts prefilled (`prefill_many`), then generated by the verify step and, from the same prefill again, by the
plain greedy decode; the two generations against each other and the records, and the drafts' acceptance.  Real
weights; GLM53_MTP_GEN = users a row:drafts a step, comma-separated, each on the same load (default 2:1; 1 user a row
takes the first 8 records).  Run (a device test):
    GLM53_DEVICE_TEST=1 GLM53_MTP=1 pytest models/demos/blackhole/glm53_flash/tests/test_mtp_generator.py -s
"""

from __future__ import annotations

import json
import os
import time
from pathlib import Path

import pytest
import torch

pytestmark = pytest.mark.skipif(
    os.environ.get("GLM53_DEVICE_TEST") != "1", reason="a device test: set GLM53_DEVICE_TEST=1"
)
ttnn = pytest.importorskip("ttnn")

from models.demos.blackhole.glm53_flash.checkpoint import Glm53Checkpoint  # noqa: E402
from models.demos.blackhole.glm53_flash.ttnn.common import DEVICE_PARAMS_TRACE, MESH_SHAPE, ROWS  # noqa: E402
from models.demos.blackhole.glm53_flash.ttnn.generator import Glm53Generator  # noqa: E402
from models.demos.blackhole.glm53_flash.ttnn.model import TtGlm53Model  # noqa: E402

RECORDS = Path(__file__).resolve().parents[1] / "tools" / "acceptance" / "greedy-v1"
CONFIGS = [(int(c.split(":")[0]), int(c.split(":")[1])) for c in os.environ.get("GLM53_MTP_GEN", "2:1").split(",")]


@pytest.mark.timeout(1500)
@pytest.mark.parametrize("mesh_device", [MESH_SHAPE], indirect=True)
@pytest.mark.parametrize("device_params", [DEVICE_PARAMS_TRACE], indirect=True)
def test_mtp_generator(mesh_device):
    t0 = time.time()
    model = TtGlm53Model(mesh_device, Glm53Checkpoint(), max_seq=512, mtp=True)
    print(f"loaded in {time.time() - t0:.0f}s", flush=True)
    for users, drafts in CONFIGS:
        print(f"== {users} users a row, {drafts} draft(s)")
        generate(model, users, drafts)


def generate(model, USERS: int, DRAFTS: int) -> None:
    """One generator (`USERS` users a row, `DRAFTS` drafts a step) through the records, then released."""
    gen = Glm53Generator(model, USERS, chunk=128, spec=DRAFTS)
    print(f"warm-up: {gen.warmup(greedy=True, logits=False, traced=(128,))}", flush=True)
    paths = sorted(RECORDS.glob("*.json"))[: ROWS * USERS]
    records = [json.loads(p.read_text()) for p in paths]
    names = [p.stem for p in paths]
    slots = [(k % ROWS) * USERS + k // ROWS for k in range(len(records))]  # spread over the rows
    prompts = [r["prompt_token_ids"] for r in records]
    wants = [r["generated_token_ids"] for r in records]
    n = gen.slots

    def prefill():
        logits = gen.prefill_many(list(zip(slots, prompts)))
        return [int(x.argmax()) for x in logits]

    # the plain greedy decode
    firsts = prefill()
    plain = [[f] for f in firsts]
    pos = [len(p) for p in prompts]
    while any(len(o) < len(w) for o, w in zip(plain, wants)):
        tokens = torch.zeros(n, dtype=torch.int64)
        positions = torch.full((n,), -1, dtype=torch.int64)
        for k, s in enumerate(slots):
            tokens[s], positions[s] = plain[k][-1], pos[k]
        ids = gen.decode(tokens, positions, greedy=True)
        for k, s in enumerate(slots):
            plain[k].append(int(ids[s]))
            pos[k] += 1

    # the verify step, from the same prefill again
    gen.first.clear()
    firsts = prefill()
    out = [[f] for f in firsts]
    tok = list(firsts)
    draft = [list(gen.first[s]) if DRAFTS > 1 else [gen.first[s]] for s in slots]
    pos = [len(p) for p in prompts]
    keep = [DRAFTS] * len(slots)
    steps, accepted, tried2, accepted2 = ([0] * len(slots) for _ in range(4))
    while any(len(o) < len(w) for o, w in zip(out, wants)):
        tokens = torch.zeros(n, DRAFTS + 1, dtype=torch.int64)
        positions = torch.full((n, DRAFTS + 1), -1, dtype=torch.int64)
        flags = torch.full((n,), DRAFTS, dtype=torch.int64)
        for k, s in enumerate(slots):
            tokens[s] = torch.tensor([tok[k], *draft[k]])
            positions[s] = torch.arange(pos[k], pos[k] + DRAFTS + 1)
            flags[s] = keep[k]
        ids, *levels = gen.verify(tokens, positions, flags)
        for k, s in enumerate(slots):
            g = [int(x) for x in ids[s]]  # the greedy id after the token and after each draft
            a = 0
            while a < DRAFTS and draft[k][a] == g[a]:
                a += 1
            if len(out[k]) < len(wants[k]):
                steps[k] += 1
                accepted[k] += a >= 1
                tried2[k] += DRAFTS > 1 and a >= 1
                accepted2[k] += DRAFTS > 1 and a >= 2
            out[k] += [*draft[k][:a], g[a]]
            keep[k], pos[k], tok[k] = a, pos[k] + a + 1, g[a]
            draft[k] = [int(level[s, a]) for level in levels]  # the MTP layer's drafts from slot a

    def prefix(a, b):
        m = 0
        while m < min(len(a), len(b)) and a[m] == b[m]:
            m += 1
        return m

    same = 0
    for k, name in enumerate(names):
        w = len(wants[k])
        p_rec, s_rec, s_p = (
            prefix(plain[k][:w], wants[k]),
            prefix(out[k][:w], wants[k]),
            prefix(out[k][:w], plain[k][:w]),
        )
        same += s_p == w
        print(
            f"{name:10s}: plain/record {p_rec:2d}, spec/record {s_rec:2d}, spec/plain {s_p:2d} of {w}; drafts "
            f"accepted {accepted[k]} / {steps[k]}",
            flush=True,
        )
    acceptance = sum(accepted) / max(1, sum(steps))
    second = f", the second draft {sum(accepted2) / max(1, sum(tried2)):.4f} (given the first)" if DRAFTS > 1 else ""
    print(
        f"{USERS} users a row, {DRAFTS} draft(s): spec equals plain on {same} / {len(names)}; acceptance "
        f"{acceptance:.4f}{second}; generator counts {gen.counts}",
        flush=True,
    )
    gen.release()
    for st in gen.states:
        st.deallocate()
    assert acceptance > 0.5, "the drafts are mostly rejected"
