# -*- coding: utf-8 -*-
"""The KDA verify step's state read ahead (GLM53_KDA_D2, ttnn/kda_d2.py): copies of recurrent_decode_step's chunked-form kernels with their CB indices, compile-time and
runtime args offset by D2_CB / D2_CT / D2_RT and kernel_main renamed, for the fused prepare + recurrence program.
The code is otherwise the tree's, line for line (the same values)."""
import pathlib
import re
import sys

# python3 kda_d2_copies.py [TREE (default: this file's tree)] [OUT (default: ttnn/kernels/kda_d2)]
_ROOT = pathlib.Path(__file__).resolve().parents[5]
TREE = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else _ROOT
OUT = (
    pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else _ROOT / "models/demos/blackhole/glm53_flash/ttnn/kernels/kda_d2"
)
K = TREE / "ttnn/cpp/ttnn/operations/experimental/kda/recurrent_decode_step/device/kernels"
HDR = (
    "#pragma once\n// A copy of recurrent_decode_step/device/kernels/{src} (ttnn/kda_d2.py): CB indices +\n"
    "// D2_CB, CT args + D2_CT, RT args + D2_RT, kernel_main -> {fn}, the read-ahead / fused hooks.  Generated by\n"
    "// models/demos/blackhole/glm53_flash/tools/kda_d2_copies.py from the op's kernel: make it again when that changes.\n"
    "#ifndef D2_CB\n#define D2_CB 0\n#endif\n#ifndef D2_CT\n#define D2_CT 0\n#endif\n#ifndef D2_RT\n#define D2_RT 0\n#endif\n"
)


def common(s):
    s = re.sub(r"get_arg_val<uint32_t>\((\d+)\)", r"get_arg_val<uint32_t>(D2_RT + \1)", s)
    s = re.sub(r"get_compile_time_arg_val\((\d+)\)", r"get_compile_time_arg_val(D2_CT + \1)", s)
    s = re.sub(r"TensorAccessorArgs<(\d+)>\(\)", r"TensorAccessorArgs<D2_CT + \1>()", s)
    # CB constants: "CB_X = n" inside lines declaring constexpr CB indices
    out = []
    for line in s.splitlines(keepends=True):
        if re.match(r"\s*constexpr uint32_t CB_", line):
            line = re.sub(r"\b(CB_\w+) = (\d+)", r"\1 = D2_CB + \2", line)
        out.append(line)
    return "".join(out)


def fix(name, fn, extra):
    src = (K / name).read_text()
    s = common(src)
    n = s.count("void kernel_main() {")
    assert n == 1, (name, n)
    s = s.replace("void kernel_main() {", f"void {fn}() {{")
    s = extra(s)
    # drop the license header lines (kept in the original)
    (OUT / (fn + ".hpp")).write_text(HDR.format(src=name, fn=fn) + s)


def reader_extra(s):
    a = "            if (u != start) {\n                read_dram(u, nb, sa);\n            }\n"
    assert s.count(a) == 1
    b = (
        "#if D2_PREFETCH_ALL  // (the fused form: every batch's state was issued at the start: the saved slot only)\n"
        "            if (u != start) {\n                read_slot(u, nb);\n            }\n#else\n" + a + "#endif\n"
    )
    s = s.replace(
        a, b + "            D2_ROWS_HOOK(u == start);  // (the fused form: the prepare outputs this core reads ready)\n"
    )
    # the prologue: with D2_PREFETCH_ALL every batch's state into CB_S at once (CB_S holds all of a core's units)
    a = (
        "    if (count > 0) {\n        const uint32_t nb0 = N - start % N < count ? N - start % N : count;\n"
        "        sc.reserve_back(nb0 * N);\n        read_dram(start, nb0, sc.get_write_ptr());\n    }\n"
    )
    assert s.count(a) == 1, "prologue"
    b = (
        "#if D2_PREFETCH_ALL\n    if (count > 0) {  // (the fused form: all batches' state, under the prepare's work)\n"
        "        const uint32_t nb0 = N - start % N < count ? N - start % N : count;\n"
        "        sc.reserve_back(count * N);\n"
        "        read_slot(start, nb0);\n"
        "        for (uint32_t u = start, t = 0; u < start + count;) {\n"
        "            const uint32_t nb = N - u % N < start + count - u ? N - u % N : start + count - u;\n"
        "            read_state(u, nb, sc.get_write_ptr(), t);\n"
        "            t += nb * N;\n            u += nb;\n        }\n    }\n#else\n" + a + "#endif\n"
    )
    s = s.replace(a, b)
    # read_dram split into read_slot / read_state (read_dram = both, as before)
    a = "    auto read_dram = [&](uint32_t u, uint32_t nb, uint32_t sa) {\n"
    assert s.count(a) == 1, "read_dram"
    i = s.index(a)
    j = s.index("    };\n", i) + len("    };\n")
    body = s[i:j]
    new = (
        "    auto read_slot = [&](uint32_t u, uint32_t nb) {\n"
        "        const uint32_t slot_bytes = V_OFF + nb * V_BLOCK;\n"
        "        for (uint32_t i = 0; i * PAGE < slot_bytes; ++i) {\n"
        "            const uint32_t n_bytes = slot_bytes - i * PAGE < PAGE ? slot_bytes - i * PAGE : PAGE;\n"
        "            noc_async_read(s_saved_src.get_noc_addr(u * SLOT_PAGES + i), st_old + i * PAGE, n_bytes);\n"
        "        }\n    };\n"
        "    // S0 of the batch's nb blocks into CB_S from sa, t0 tiles past it\n"
        "    auto read_state = [&](uint32_t u, uint32_t nb, uint32_t sa, uint32_t t0) {\n"
        "        const uint32_t p = u / N, j0 = u % N;\n"
        "        for (uint32_t b = 0; b < nb; ++b) {\n"
        "            for (uint32_t i = 0; i < N; ++i) {\n"
        "                const uint32_t page = p * N * N + i * N + j0 + b;\n"
        "                noc_async_read(s_state.get_noc_addr(page), sa + wrapped(CB_S, t0 + b * N + i, s_tile), s_tile);\n"
        "            }\n        }\n    };\n"
        "    auto read_dram = [&](uint32_t u, uint32_t nb, uint32_t sa) {\n"
        "        read_slot(u, nb);\n        read_state(u, nb, sa, 0);\n    };\n"
    )
    # check the original body is the slot loop then the state loop (the same reads, in the same order)
    assert "s_saved_src.get_noc_addr(u * SLOT_PAGES + i)" in body and "s_state.get_noc_addr(page)" in body
    new = new.replace(
        "    auto read_state = [&](uint32_t u, uint32_t nb, uint32_t sa, uint32_t t0) {\n",
        "    auto read_state = [&](uint32_t u, uint32_t nb, uint32_t sa, uint32_t t0) {\n"
        "#if D2_STATE_RESIDENT  // (the read-ahead form: the prepare program read it into CB_S's memory already)\n"
        "        return;\n#endif\n",
    )
    s = s[:i] + new + s[j:]
    return (
        "#ifndef D2_PREFETCH_ALL\n#define D2_PREFETCH_ALL 0\n#endif\n"
        "#ifndef D2_STATE_RESIDENT\n#define D2_STATE_RESIDENT 0\n#endif\n"
    ) + s


def compute_extra(s):
    a = "    compute_kernel_hw_startup(CB_KQP, CB_KM, CB_G);\n"
    assert s.count(a) == 1
    return s.replace(
        a,
        "#if !D2_NO_STARTUP  // (the fused form: after decode_prepare's startup, the same fp32 formats)\n"
        + a
        + "#endif\n",
    )


fix("dataflow/reader_recurrent_decode_chunk.cpp", "d2_chunk_reader", reader_extra)
fix("dataflow/writer_recurrent_decode_chunk.cpp", "d2_chunk_writer", lambda s: s)
fix("compute/recurrent_decode_chunk.cpp", "d2_chunk_compute", compute_extra)
print("ok")
